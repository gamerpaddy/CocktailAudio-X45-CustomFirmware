const unsigned char *x45_glyph(int c)
{
	if (c < GLYPH_FIRST || c > GLYPH_LAST)
		c = '?';
	return font5x7[c - GLYPH_FIRST];
}

int x45_font_first(void) { return GLYPH_FIRST; }
int x45_font_last(void)  { return GLYPH_LAST; }

/* Hand-authored tables acquire typos. This catches the mechanical classes of
 * mistake: a glyph that is accidentally blank, a glyph that duplicates another
 * (almost always a copy/paste slip), and any column with bit 7 set, which would
 * mean a row below the 7-pixel cell. Returns the number of problems found and
 * describes each on stderr. */
int x45_font_selfcheck(void)
{
	int n = GLYPH_LAST - GLYPH_FIRST + 1;
	int i, j, k, problems = 0;

	for (i = 0; i < n; i++) {
		int c = GLYPH_FIRST + i;
		int blank = 1;

		for (k = 0; k < 5; k++) {
			if (font5x7[i][k])
				blank = 0;
			if (font5x7[i][k] & 0x80) {
				fprintf(stderr,
					"font: '%c' (0x%02X) column %d has bit 7 set (0x%02X)\n",
					c, c, k, font5x7[i][k]);
				problems++;
			}
		}
		if (blank && c != ' ') {
			fprintf(stderr, "font: '%c' (0x%02X) is blank\n", c, c);
			problems++;
		}
		for (j = 0; j < i; j++) {
			int cj = GLYPH_FIRST + j;
			if (cj == ' ' || c == ' ')
				continue;
			if (!memcmp(font5x7[i], font5x7[j], 5)) {
				fprintf(stderr,
					"font: '%c' (0x%02X) is identical to '%c' (0x%02X)\n",
					c, c, cj, cj);
				problems++;
			}
		}
	}
	return problems;
}
